import React, { useState } from 'react'
import { useNavigate } from 'react-router-dom'
import { toast } from 'react-toastify'
import { Building2, Plus, ArrowLeft, MapPin, DollarSign, Info } from 'lucide-react'
import API from '../../api/axios'
import Navbar from '../../components/Navbar'

const AddTheatrePage = () => {
  const navigate = useNavigate()
  const [loading, setLoading] = useState(false)

  const [form, setForm] = useState({
    theatreName: '',
    location: '',
    balconySeatPrice: '',
    middleSeatPrice: '',
    lowerSeatPrice: '',
  })

  const handleChange = (e) => {
    setForm((prev) => ({ ...prev, [e.target.name]: e.target.value }))
  }

  const validate = () => {
    if (!form.theatreName.trim()) { toast.error('Theatre name is required'); return false }
    if (!form.location.trim()) { toast.error('Location is required'); return false }
    if (!form.balconySeatPrice || Number(form.balconySeatPrice) <= 0) {
      toast.error('Enter a valid balcony seat price'); return false
    }
    if (!form.middleSeatPrice || Number(form.middleSeatPrice) <= 0) {
      toast.error('Enter a valid middle seat price'); return false
    }
    if (!form.lowerSeatPrice || Number(form.lowerSeatPrice) <= 0) {
      toast.error('Enter a valid lower seat price'); return false
    }
    return true
  }

  const handleSubmit = async (e) => {
    e.preventDefault()
    if (!validate()) return
    setLoading(true)
    try {
      await API.post('/theatre', {
        theatreName: form.theatreName.trim(),
        location: form.location.trim(),
        balconySeatPrice: Number(form.balconySeatPrice),
        middleSeatPrice: Number(form.middleSeatPrice),
        lowerSeatPrice: Number(form.lowerSeatPrice),
      })
      toast.success(`Theatre "${form.theatreName}" added successfully!`)
      navigate('/admin')
    } catch (err) {
      toast.error(err.response?.data?.message || 'Failed to add theatre')
    } finally {
      setLoading(false)
    }
  }

  const TIERS = [
    { key: 'balconySeatPrice', label: 'Balcony (Premium)', desc: 'Top rows, best view', color: 'text-purple-400', rows: '3 rows × 10 seats = 30 seats' },
    { key: 'middleSeatPrice', label: 'Middle', desc: 'Central section', color: 'text-[#00a8e1]', rows: '4 rows × 10 seats = 40 seats' },
    { key: 'lowerSeatPrice', label: 'Lower (Front)', desc: 'Front rows', color: 'text-green-400', rows: '3 rows × 10 seats = 30 seats' },
  ]

  return (
    <div className="min-h-screen bg-[#0f171e]">
      <Navbar />

      <div className="pt-24 pb-16 max-w-2xl mx-auto px-4 sm:px-6 lg:px-8">
        {/* Header */}
        <div className="flex items-center gap-4 mb-8">
          <button
            onClick={() => navigate('/admin')}
            className="text-[#8197a4] hover:text-white transition-colors duration-200"
            aria-label="Back"
          >
            <ArrowLeft className="w-5 h-5" />
          </button>
          <div>
            <h1 className="text-2xl font-black text-white flex items-center gap-2">
              <Building2 className="w-6 h-6 text-[#00a8e1]" />
              Add New Theatre
            </h1>
            <p className="text-[#8197a4] text-sm mt-0.5">Seat layouts are auto-generated by the system</p>
          </div>
        </div>

        <form onSubmit={handleSubmit} className="space-y-6">
          {/* Theatre Name */}
          <div>
            <label className="block text-sm font-medium text-[#c0cdd5] mb-1.5">Theatre Name *</label>
            <input
              type="text"
              name="theatreName"
              value={form.theatreName}
              onChange={handleChange}
              placeholder="e.g. PVR Cinemas Phoenix"
              className="w-full bg-[#1a242f] border border-[#253241] text-white placeholder-[#8197a4] focus:border-[#00a8e1] focus:outline-none rounded-lg px-4 py-3 transition-colors duration-200"
            />
          </div>

          {/* Location */}
          <div>
            <label className="block text-sm font-medium text-[#c0cdd5] mb-1.5">
              <span className="flex items-center gap-1.5">
                <MapPin className="w-4 h-4" /> Location *
              </span>
            </label>
            <input
              type="text"
              name="location"
              value={form.location}
              onChange={handleChange}
              placeholder="e.g. Phoenix Mall, Bangalore"
              className="w-full bg-[#1a242f] border border-[#253241] text-white placeholder-[#8197a4] focus:border-[#00a8e1] focus:outline-none rounded-lg px-4 py-3 transition-colors duration-200"
            />
          </div>

          {/* Seat Pricing */}
          <div>
            <div className="flex items-center gap-2 mb-4">
              <DollarSign className="w-5 h-5 text-[#00a8e1]" />
              <h2 className="text-white font-bold text-base">Seat Pricing (₹)</h2>
            </div>

            {/* Info banner */}
            <div className="bg-[#1a242f] border border-[#253241] rounded-xl p-4 mb-4">
              <div className="flex items-start gap-2">
                <Info className="w-4 h-4 text-[#00a8e1] mt-0.5 flex-shrink-0" />
                <p className="text-[#8197a4] text-xs leading-relaxed">
                  The seat layout (10 rows × 10 columns = 100 seats total) is auto-generated by the backend.
                  Set pricing per tier below.
                </p>
              </div>
            </div>

            <div className="space-y-4">
              {TIERS.map(({ key, label, desc, color, rows }) => (
                <div key={key} className="bg-[#1a242f] border border-[#253241] rounded-xl p-5 hover:border-[#253241]/80 transition-colors">
                  <div className="flex items-start justify-between mb-3">
                    <div>
                      <p className={`font-semibold text-sm ${color}`}>{label}</p>
                      <p className="text-[#8197a4] text-xs">{desc}</p>
                      <p className="text-[#8197a4] text-xs mt-0.5">{rows}</p>
                    </div>
                  </div>
                  <div className="relative">
                    <span className="absolute left-3 top-1/2 -translate-y-1/2 text-[#8197a4] font-medium">₹</span>
                    <input
                      type="number"
                      name={key}
                      value={form[key]}
                      onChange={handleChange}
                      placeholder="0"
                      min="1"
                      className="w-full bg-[#0f171e] border border-[#253241] text-white placeholder-[#8197a4] focus:border-[#00a8e1] focus:outline-none rounded-lg px-4 py-3 pl-7 transition-colors duration-200"
                    />
                  </div>
                </div>
              ))}
            </div>
          </div>

          {/* Pricing preview */}
          {(form.balconySeatPrice || form.middleSeatPrice || form.lowerSeatPrice) && (
            <div className="bg-[#1a242f] border border-[#00a8e1]/30 rounded-xl p-4">
              <p className="text-[#00a8e1] text-sm font-semibold mb-2">Pricing Preview</p>
              <div className="space-y-1 text-sm">
                {form.balconySeatPrice && (
                  <div className="flex justify-between"><span className="text-[#8197a4]">Balcony</span><span className="text-white font-medium">₹{form.balconySeatPrice}/seat</span></div>
                )}
                {form.middleSeatPrice && (
                  <div className="flex justify-between"><span className="text-[#8197a4]">Middle</span><span className="text-white font-medium">₹{form.middleSeatPrice}/seat</span></div>
                )}
                {form.lowerSeatPrice && (
                  <div className="flex justify-between"><span className="text-[#8197a4]">Lower</span><span className="text-white font-medium">₹{form.lowerSeatPrice}/seat</span></div>
                )}
              </div>
            </div>
          )}

          {/* Submit buttons */}
          <div className="flex gap-4 pt-2">
            <button
              type="button"
              onClick={() => navigate('/admin')}
              className="flex-1 bg-[#1a242f] hover:bg-[#253241] border border-[#253241] text-[#c0cdd5] font-semibold px-6 py-3 rounded-lg transition-all duration-200"
            >
              Cancel
            </button>
            <button
              type="submit"
              disabled={loading}
              className="flex-1 flex items-center justify-center gap-2 bg-[#00a8e1] hover:bg-[#0891c9] disabled:opacity-60 text-white font-semibold px-6 py-3 rounded-lg transition-all duration-200"
            >
              {loading ? (
                <><div className="w-4 h-4 border-2 border-white/30 border-t-white rounded-full animate-spin" /> Adding...</>
              ) : (
                <><Plus className="w-4 h-4" /> Add Theatre</>
              )}
            </button>
          </div>
        </form>
      </div>
    </div>
  )
}

export default AddTheatrePage
